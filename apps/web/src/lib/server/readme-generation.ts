import { createHash } from 'node:crypto';
import type { Buckets } from '@lazydata/validator';
import { templateReadmes } from './template-readmes.ts';

export const notesMarker = '<!-- notes -->';
export const generatedComment = '<!-- Generated by Lazydata from datapackage.json and buckets.csv. Text above the notes marker is replaced on Save; text below it is kept. -->';

function cell(value: unknown): string {
  const text = Array.isArray(value) ? value.join(', ') : typeof value === 'string' || typeof value === 'number' ? String(value) : '';
  return text.replace(/[\r\n\u2028\u2029]/g, ' ').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(/[\\`*_{}[\]()#+!|~]/g, '\\$&');
}

function prose(value: string): string {
  return value.split(/\r\n?|\n|\u2028|\u2029/).map((line) => cell(line.trim())
    .replace(/[-=]/g, '\\$&').replace(/^(\d+)\./, '$1\\.')).join('\n');
}

function badge(label: string, value: string, color: string): string {
  const encoded = encodeURIComponent(value.replace(/-/g, '--').replace(/_/g, '__')).replace(/[!'()*]/g,
    (char) => `%${char.charCodeAt(0).toString(16).toUpperCase()}`);
  return `![${cell(`${label}: ${value}`)}](https://img.shields.io/badge/${label}-${encoded}-${color})`;
}

function rows(value: unknown): Record<string, unknown>[] {
  return Array.isArray(value) ? value.filter((item): item is Record<string, unknown> =>
    typeof item === 'object' && item !== null && !Array.isArray(item)) : [];
}

function table(headers: string[], values: unknown[][]): string {
  const row = (values: unknown[]) => `| ${values.map(cell).join(' | ')} |`;
  return [row(headers), `| ${headers.map(() => '---').join(' | ')} |`, ...values.map(row)].join('\n');
}

function list(values: unknown[][]): string {
  return values.map((row) => row.map(cell).filter(Boolean).join(' — '))
    .filter(Boolean).map((line) => `- ${line}`).join('\n');
}

function countText(resource: Record<string, unknown>): string {
  const count = resource.count;
  if (typeof count !== 'number' || !Number.isSafeInteger(count) || count < 0) return '';
  const path = typeof resource.path === 'string' ? resource.path.toLowerCase() : '';
  const unit = /\.(csv|tsv)$/.test(path) ? 'row' : /\.(json|jsonl)$/.test(path) ? 'item' : 'file';
  return `${count} ${unit}${count === 1 ? '' : 's'}`;
}

function notes(existing: string): string {
  const marker = existing.indexOf(notesMarker);
  if (marker !== -1) return existing.slice(marker + notesMarker.length);
  const digest = createHash('sha256').update(existing).digest('hex');
  if (templateReadmes.some(({ sha256 }) => sha256 === digest)) return '\n';
  return existing ? `\n\n${existing}` : '\n';
}

export function generateReadme(data: Record<string, unknown>, buckets?: Buckets, existing = ''): string {
  const parts = [`# ${cell(data.title || data.name)}`];
  const subtitle = [cell(data.name), typeof data.created === 'string' ? cell(data.created.slice(0, 10)) : ''].filter(Boolean);
  if (subtitle.length) parts.push(`*${subtitle.join(' · ')}*`);
  const keywords = Array.isArray(data.keywords) ? data.keywords : [];
  const badges = Object.entries({ task: 'green', project: 'blue', stage: 'purple' }).flatMap(([label, color]) => {
    const keyword = keywords.find((value): value is string => typeof value === 'string' && value.startsWith(`${label}:`));
    return keyword ? [badge(label, keyword.slice(label.length + 1), color)] : [];
  });
  if (typeof data.version === 'string' && data.version) badges.push(badge('version', data.version, 'blue'));
  if (badges.length) parts.push(badges.join('\n'));
  if (typeof data.description === 'string' && data.description) parts.push(prose(data.description));
  const contributors = list(rows(data.contributors).map((row) => [row.title, row.roles]));
  if (contributors) parts.push('## Contributors', contributors);
  const sources = list(rows(data.sources).map((row) => [row.title, row.path]));
  if (sources) parts.push('## Sources', sources);
  parts.push('## Resources', table(['Resource name', 'Title', 'Path', 'Format', 'Count'],
    rows(data.resources).map((row) => [row.name, row.title, row.path, row.format, countText(row)])), '## Buckets',
    buckets ? table([buckets.labelColumn, 'Count'], buckets.rows.map((row) => [row[buckets.labelColumn], row.count]))
      : '_No buckets available._');
  return `${generatedComment}\n\n${parts.join('\n\n')}\n\n${notesMarker}${notes(existing)}`;
}
